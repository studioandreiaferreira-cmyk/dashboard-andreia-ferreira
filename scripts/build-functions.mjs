// Bundles the Supabase Edge Functions (Deno) and the local sync runner (Node) with esbuild.
import { build } from "esbuild";

const local = process.argv.includes("--local");
const common = { bundle: true, format: "esm", target: "es2022", logLevel: "warning" };

if (local) {
  await build({ ...common, platform: "node", entryPoints: ["scripts/sync-local.ts"], outfile: ".build/sync-local.mjs", packages: "external" });
} else {
  for (const fn of ["sync", "chat"]) {
    await build({
      ...common,
      platform: "neutral",
      entryPoints: [`functions-src/${fn}.ts`],
      outfile: `supabase/functions/${fn}/index.ts`,
      // Deno resolves npm packages itself.
      alias: { postgres: "npm:postgres@3.4.9" },
      external: ["npm:*"],
      banner: { js: "// Generated by scripts/build-functions.mjs from functions-src/ — do not edit.\n// @ts-nocheck" },
    });
  }
}
